# -*- coding: utf-8 -*-
"""
PM SYSTEM - COMPLETE AUTO-PM DATE / COMPLETION TEST
=====================================================

READ/WRITE TEST ON A TEMPORARY PM ONLY.

This test is intentionally independent of the GUI, login state, Personnel
objects and activity logger. It directly exercises:

    1) The real AutoPMService
    2) The real PMRepository.update_after_completion()
    3) The real WorkOrder records generated by AutoPMService
    4) The real PM last_done / next_due values in SQL Server

IMPORTANT
---------
- Existing operational PMs are NOT modified.
- Existing operational Work Orders are NOT modified.
- A uniquely named temporary PM is created.
- Temporary Work Orders are generated for that PM.
- Temporary records are deleted at the end.
- The test deliberately uses fixed historical dates so it does not wait.

Run from the project root:

    C:\\ProgramData\\anaconda3\\python.exe test_auto_pm_date_complete.py 92 4

Arguments:
    1 = equipment id (default 92)
    2 = department id (default 4)

The test covers two cycles:

Cycle 1
-------
Scheduled:        2026-04-10 10:00
Actual completion:2026-04-15 15:00
Interval:         30 days
Expected next_due by CURRENT CODE: 2026-05-15 15:00
Expected calendar +1 month:        2026-05-15 15:00

Cycle 2 (diagnostic for true monthly semantics)
-------------------------------------------------
Actual completion:2026-05-20 15:00
Expected by CURRENT CODE (+30 days): 2026-06-19 15:00
Expected calendar +1 month:          2026-06-20 15:00

Therefore the test tells us BOTH:

A) whether completion date drives next_due, and
B) whether a "monthly" PM behaves as +30 days or true calendar-month logic.
"""

from __future__ import print_function

import calendar
import sys
import uuid
from datetime import datetime, timedelta

import os as _os
sys.path.insert(0, _os.path.dirname(_os.path.dirname(_os.path.abspath(__file__))))  # project root

from database.db import SessionLocal
from database.models import PMSchedule, Equipment, Department
from database.work_order import WorkOrder
from database.pm_repository import PMRepository
from services.auto_pm_service import AutoPMService


def fmt(value):
    if value is None:
        return "-"
    return value.strftime("%Y-%m-%d %H:%M:%S")


def close_enough(a, b, seconds=1):
    if a is None or b is None:
        return False
    try:
        return abs((a - b).total_seconds()) <= seconds
    except Exception:
        return False


def add_month(dt, months=1):
    total = dt.year * 12 + (dt.month - 1) + months
    year = total // 12
    month = (total % 12) + 1
    day = min(dt.day, calendar.monthrange(year, month)[1])
    return dt.replace(year=year, month=month, day=day)


def get_reference_records(session, equipment_id, department_id):
    equipment = (
        session.query(Equipment)
        .filter(Equipment.id == equipment_id)
        .first()
    )

    department = (
        session.query(Department)
        .filter(Department.id == department_id)
        .first()
    )

    return equipment, department


def count_temp_wos(session, pm_id):
    return (
        session.query(WorkOrder)
        .filter(WorkOrder.schedule_id == pm_id)
        .count()
    )


def get_temp_wos(session, pm_id):
    return (
        session.query(WorkOrder)
        .filter(WorkOrder.schedule_id == pm_id)
        .order_by(WorkOrder.id.asc())
        .all()
    )


def run_test(equipment_id, department_id):
    session = SessionLocal()
    pm_id = None
    temp_work_order_ids = []

    scheduled_1 = datetime(2026, 4, 10, 10, 0, 0)
    completion_1 = datetime(2026, 4, 15, 15, 0, 0)

    completion_2 = datetime(2026, 5, 20, 15, 0, 0)

    interval_days = 30
    expected_cycle_1 = completion_1 + timedelta(days=interval_days)
    expected_calendar_1 = add_month(completion_1, 1)

    expected_cycle_2 = completion_2 + timedelta(days=interval_days)
    expected_calendar_2 = add_month(completion_2, 1)

    print("=" * 82)
    print("PM SYSTEM - COMPLETE REAL DATABASE AUTO PM DATE TEST")
    print("=" * 82)
    print("MODE        : TEMPORARY INTEGRATION TEST")
    print("DATABASE    : PM_Database")
    print("INTERVAL    : {} days".format(interval_days))
    print("CYCLE 1 SCHEDULED : {}".format(fmt(scheduled_1)))
    print("CYCLE 1 COMPLETE  : {}".format(fmt(completion_1)))
    print("CYCLE 2 COMPLETE  : {}".format(fmt(completion_2)))
    print()

    try:
        equipment, department = get_reference_records(
            session,
            equipment_id,
            department_id,
        )

        if not equipment:
            print("[FAIL] Equipment #{} not found.".format(equipment_id))
            return 2

        if not department:
            print("[FAIL] Department #{} not found.".format(department_id))
            return 2

        print("[REFERENCE RECORDS]")
        print("  Equipment   : #{} - {}".format(equipment.id, equipment.name))
        print("  Department  : #{} - {}".format(department.id, department.name))
        print()

        unique = uuid.uuid4().hex[:10].upper()

        pm = PMSchedule(
            title="[AUTO PM COMPLETE DATE TEST] {}".format(unique),
            equipment_id=equipment.id,
            department_id=department.id,
            technician_id=None,
            frequency="monthly",
            interval_days=interval_days,
            last_done=None,
            next_due=scheduled_1,
            checklist="TEST ONLY",
            estimated_duration=1,
            is_active=True,
            notes="Temporary automated date test - safe to delete",
            parts_required=None,
        )

        session.add(pm)
        session.commit()
        pm_id = pm.id

        print("[1/8] TEMPORARY PM CREATED")
        print("  PM ID       : #{}".format(pm_id))
        print("  Next due    : {}".format(fmt(pm.next_due)))
        print("  Active      : {}".format(pm.is_active))
        print()

        # ------------------------------------------------------------------
        # 2. Real AutoPMService creates the first WO
        # ------------------------------------------------------------------
        auto = AutoPMService(check_interval_seconds=1)
        print("[2/8] RUNNING REAL AUTOPMSERVICE")
        auto._check_and_generate()

        session.expire_all()
        pm = session.query(PMSchedule).filter(PMSchedule.id == pm_id).first()
        wos = get_temp_wos(session, pm_id)

        print("  Generated Work Orders: {}".format(len(wos)))
        print("  PM next_due          : {}".format(fmt(pm.next_due)))

        if len(wos) != 1:
            print("[FAIL] Expected exactly one generated Work Order.")
            return 1

        wo1 = wos[0]
        temp_work_order_ids.append(wo1.id)

        print("  WO #{} scheduled: {}".format(wo1.id, fmt(wo1.scheduled_date)))
        print("  WO #{} status   : {}".format(wo1.id, wo1.status))

        check_create = (
            close_enough(wo1.scheduled_date, scheduled_1)
            and close_enough(pm.next_due, scheduled_1)
        )

        if check_create:
            print("  PASS: Auto PM generated the first WO on the stored next_due")
            print("        and did not advance next_due just by generating it.")
        else:
            print("[FAIL] First generation/date preservation check failed.")
            return 1
        print()

        # ------------------------------------------------------------------
        # 3. Exact completion calculation used by final approval path
        # ------------------------------------------------------------------
        print("[3/8] APPLYING REAL PMRepository.update_after_completion()")
        pm_repo = PMRepository(SessionLocal)
        result = pm_repo.update_after_completion(pm_id, completion_1)

        print("  Repository result : {}".format(result))

        session.expire_all()
        pm = session.query(PMSchedule).filter(PMSchedule.id == pm_id).first()

        print("  Stored last_done   : {}".format(fmt(pm.last_done)))
        print("  Stored next_due    : {}".format(fmt(pm.next_due)))
        print("  Expected +30 days : {}".format(fmt(expected_cycle_1)))
        print("  Calendar +1 month : {}".format(fmt(expected_calendar_1)))

        completion_logic_ok = (
            close_enough(pm.last_done, completion_1)
            and close_enough(pm.next_due, expected_cycle_1)
        )

        if completion_logic_ok:
            print("  PASS: last_done and next_due are based on ACTUAL completion.")
        else:
            print("[FAIL] Completion-date calculation does not match the current")
            print("       repository implementation expectation.")
            return 1
        print()

        # ------------------------------------------------------------------
        # 4. Real AutoPMService creates next cycle at the stored next_due
        # ------------------------------------------------------------------
        print("[4/8] RUNNING REAL AUTOPMSERVICE FOR THE NEXT CYCLE")
        auto._check_and_generate()

        session.expire_all()
        wos = get_temp_wos(session, pm_id)
        pm = session.query(PMSchedule).filter(PMSchedule.id == pm_id).first()

        print("  Total Work Orders : {}".format(len(wos)))
        for wo in wos:
            print(
                "  WO #{} | scheduled={} | status={}".format(
                    wo.id,
                    fmt(wo.scheduled_date),
                    wo.status,
                )
            )

        if len(wos) == 2:
            temp_work_order_ids.append(wos[1].id)

        second_generation_ok = (
            len(wos) == 2
            and close_enough(wos[1].scheduled_date, expected_cycle_1)
        )

        if second_generation_ok:
            print("  PASS: second automatic WO is scheduled from the")
            print("        completion-based next_due date.")
        else:
            print("[FAIL] Second automatic generation/date check failed.")
            return 1
        print()

        # ------------------------------------------------------------------
        # 5. Second completion - diagnostic for true monthly semantics
        # ------------------------------------------------------------------
        print("[5/8] SECOND COMPLETION DATE DIAGNOSTIC")
        print("  Simulated actual completion : {}".format(fmt(completion_2)))
        print("  Applying the SAME real repository method...")

        result2 = pm_repo.update_after_completion(pm_id, completion_2)

        print("  Repository result : {}".format(result2))

        session.expire_all()
        pm = session.query(PMSchedule).filter(PMSchedule.id == pm_id).first()

        print("  Stored last_done   : {}".format(fmt(pm.last_done)))
        print("  Stored next_due    : {}".format(fmt(pm.next_due)))
        print("  Current code +30   : {}".format(fmt(expected_cycle_2)))
        print("  Calendar +1 month  : {}".format(fmt(expected_calendar_2)))

        second_completion_ok = close_enough(pm.last_done, completion_2)
        second_interval_ok = close_enough(pm.next_due, expected_cycle_2)
        calendar_month_ok = close_enough(pm.next_due, expected_calendar_2)

        if second_completion_ok and second_interval_ok:
            print("  PASS: actual completion drives the next cycle AGAIN.")
        else:
            print("[FAIL] Second completion calculation failed.")
            return 1

        print()
        print("  MONTHLY SEMANTICS:")
        if calendar_month_ok:
            print("  PASS: this completion also equals true calendar +1 month.")
        else:
            print("  NOTE: current PM is NOT using true calendar-month arithmetic.")
            print("        It is using interval_days = 30.")
            print("        This is expected from the current repository code.")
        print()

        # ------------------------------------------------------------------
        # 6. Final AutoPM generation from the second next_due
        # ------------------------------------------------------------------
        print("[6/8] FINAL AUTOPM GENERATION CHECK")
        auto._check_and_generate()

        session.expire_all()
        wos = get_temp_wos(session, pm_id)
        pm = session.query(PMSchedule).filter(PMSchedule.id == pm_id).first()

        for wo in wos:
            if wo.id not in temp_work_order_ids:
                temp_work_order_ids.append(wo.id)

        print("  Total Work Orders : {}".format(len(wos)))
        if len(wos) >= 3:
            newest = wos[-1]
            print("  Newest WO #{} scheduled: {}".format(newest.id, fmt(newest.scheduled_date)))
            print("  PM next_due           : {}".format(fmt(pm.next_due)))

            final_generation_ok = close_enough(newest.scheduled_date, expected_cycle_2)
        else:
            final_generation_ok = False

        if final_generation_ok:
            print("  PASS: Auto PM generated the third cycle from the")
            print("        second completion-based next_due.")
        else:
            print("[FAIL] Final Auto PM generation/date check failed.")
            return 1
        print()

        # ------------------------------------------------------------------
        # 7. Read-back summary from real SQLAlchemy session
        # ------------------------------------------------------------------
        print("[7/8] FINAL DATABASE READ-BACK")
        session.expire_all()
        pm = session.query(PMSchedule).filter(PMSchedule.id == pm_id).first()
        wos = get_temp_wos(session, pm_id)

        print("  PM ID            : #{}".format(pm.id))
        print("  PM last_done     : {}".format(fmt(pm.last_done)))
        print("  PM next_due      : {}".format(fmt(pm.next_due)))
        print("  Linked WorkOrders: {}".format(len(wos)))
        for wo in wos:
            print("    WO #{} -> {}".format(wo.id, fmt(wo.scheduled_date)))
        print()

        # ------------------------------------------------------------------
        # 8. Cleanup
        # ------------------------------------------------------------------
        print("[8/8] CLEANUP")
        print("  Removing temporary Work Orders and PM...")

        for wo in list(wos):
            session.delete(wo)

        session.flush()
        session.delete(pm)
        session.commit()

        print("  Cleanup completed.")
        print()

        print("=" * 82)
        print("FINAL RESULT")
        print("=" * 82)
        print("PASS: Completion-date anchoring is working.")
        print("PASS: Auto PM generates from the stored completion-based next_due.")
        print()

        if calendar_month_ok:
            print("MONTHLY RESULT: Calendar-month behavior also matches for")
            print("                the tested completion date.")
        else:
            print("MONTHLY RESULT: IMPORTANT - current code is 30-day based, NOT")
            print("                true calendar-month based.")
            print("                Example:")
            print("                  May 20 + 30 days  = June 19")
            print("                  May 20 + 1 month  = June 20")
        print("=" * 82)

        return 0

    except Exception as exc:
        print()
        print("=" * 82)
        print("FINAL RESULT: ERROR")
        print("=" * 82)
        print("ERROR: {}".format(exc))
        print()
        print("The test will attempt cleanup.")
        print("=" * 82)
        return 3

    finally:
        try:
            if pm_id is not None:
                # Best-effort cleanup in a fresh session in case the main test
                # failed before its normal cleanup section.
                session.rollback()
                remaining_wos = (
                    session.query(WorkOrder)
                    .filter(WorkOrder.schedule_id == pm_id)
                    .all()
                )
                for wo in remaining_wos:
                    session.delete(wo)
                session.flush()

                remaining_pm = (
                    session.query(PMSchedule)
                    .filter(PMSchedule.id == pm_id)
                    .first()
                )
                if remaining_pm:
                    session.delete(remaining_pm)

                session.commit()
        except Exception:
            try:
                session.rollback()
            except Exception:
                pass

        try:
            session.close()
        except Exception:
            pass


def main():
    try:
        equipment_id = int(sys.argv[1]) if len(sys.argv) > 1 else 92
        department_id = int(sys.argv[2]) if len(sys.argv) > 2 else 4
    except ValueError:
        print("Usage: python test_auto_pm_date_complete.py [equipment_id] [department_id]")
        return 2

    return run_test(equipment_id, department_id)


if __name__ == "__main__":
    sys.exit(main())
